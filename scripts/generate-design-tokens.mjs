import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const scriptsDir = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(scriptsDir, "..");

export async function loadTokens(tokenPath) {
  const raw = await readFile(tokenPath, "utf8");
  const tokens = JSON.parse(raw);

  if (tokens?.meta?.version !== 1 || !tokens?.color?.light || !tokens?.color?.dark) {
    throw new Error("Unsupported or incomplete design token document");
  }

  return tokens;
}

function kebabCase(value) {
  return value.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();
}

function dartColor(hex) {
  const normalized = hex.slice(1).toUpperCase();
  const argb = normalized.length === 8
    ? `${normalized.slice(6)}${normalized.slice(0, 6)}`
    : `FF${normalized}`;
  return `Color(0x${argb})`;
}

function cssRgb(hex) {
  return hex
    .slice(1, 7)
    .match(/.{2}/g)
    .map((value) => Number.parseInt(value, 16))
    .join(", ");
}

function cssThemeVariables(theme) {
  return Object.entries(theme)
    .flatMap(([name, value]) => {
      const tokenName = kebabCase(name);
      const lines = [`  --color-${tokenName}: ${value};`];
      if (/^#[0-9a-f]{6}$/i.test(value)) {
        lines.push(`  --color-${tokenName}-rgb: ${cssRgb(value)};`);
      }
      return lines;
    })
    .join("\n");
}

export function renderCss(tokens) {
  const sizeLines = [
    ...Object.entries(tokens.size.spacing).map(
      ([name, value]) => `  --space-${kebabCase(name)}: ${value}px;`,
    ),
    ...Object.entries(tokens.size.radius).map(
      ([name, value]) => `  --radius-${kebabCase(name)}: ${value}px;`,
    ),
    ...Object.entries(tokens.size.target).map(
      ([name, value]) => `  --target-${kebabCase(name)}: ${value}px;`,
    ),
    ...Object.entries(tokens.size.control).map(
      ([name, value]) => `  --control-${kebabCase(name)}: ${value}px;`,
    ),
  ].join("\n");
  const typeLines = [
    ...Object.entries(tokens.type.size).map(
      ([name, value]) => `  --type-${kebabCase(name)}: ${value}px;`,
    ),
    ...Object.entries(tokens.type.lineHeight).map(
      ([name, value]) => `  --leading-${kebabCase(name)}: ${value};`,
    ),
  ].join("\n");
  const shadowLines = Object.entries(tokens.shadow)
    .map(([name, value]) => `  --shadow-${kebabCase(name)}: ${value};`)
    .join("\n");

  return `/* Generated by scripts/generate-design-tokens.mjs. Do not edit. */\n:root {\n${cssThemeVariables(tokens.color.light)}\n${sizeLines}\n${typeLines}\n${shadowLines}\n}\n\n.dark {\n${cssThemeVariables(tokens.color.dark)}\n}\n`;
}

function dartColorClass(name, colors) {
  const fields = Object.entries(colors)
    .map(([field, value]) => `  static const ${field} = ${dartColor(value)};`)
    .join("\n");
  return `abstract final class ${name} {\n${fields}\n}`;
}

function dartNumberFields(prefix, values) {
  return Object.entries(values)
    .map(([name, value]) => {
      const field = `${prefix}${name[0].toUpperCase()}${name.slice(1)}`;
      return `  static const double ${field} = ${value};`;
    })
    .join("\n");
}

export function renderDart(tokens) {
  const sizeFields = [
    dartNumberFields("space", tokens.size.spacing),
    dartNumberFields("radius", tokens.size.radius),
    dartNumberFields("target", tokens.size.target),
    dartNumberFields("control", tokens.size.control),
    dartNumberFields("type", tokens.type.size),
  ].join("\n");

  return `// Generated by scripts/generate-design-tokens.mjs. Do not edit.\nimport 'package:flutter/material.dart';\n\n${dartColorClass("DesignColorsLight", tokens.color.light)}\n\n${dartColorClass("DesignColorsDark", tokens.color.dark)}\n\nabstract final class DesignSize {\n${sizeFields}\n}\n`;
}

function channelToLinear(channel) {
  const value = channel / 255;
  return value <= 0.04045 ? value / 12.92 : ((value + 0.055) / 1.055) ** 2.4;
}

function luminance(hex) {
  const rgb = hex.slice(1, 7).match(/.{2}/g).map((value) => Number.parseInt(value, 16));
  const [red, green, blue] = rgb.map(channelToLinear);
  return 0.2126 * red + 0.7152 * green + 0.0722 * blue;
}

export function contrastRatio(foreground, background) {
  const lighter = Math.max(luminance(foreground), luminance(background));
  const darker = Math.min(luminance(foreground), luminance(background));
  return (lighter + 0.05) / (darker + 0.05);
}

export function assertAccessiblePairs(tokens) {
  for (const pair of tokens.accessibilityPairs) {
    const theme = tokens.color[pair.theme];
    const foreground = theme[pair.foreground];
    const background = theme[pair.background];
    if (!foreground || !background) {
      throw new Error(`Unknown color in accessibility pair ${JSON.stringify(pair)}`);
    }
    const ratio = contrastRatio(foreground, background);
    if (ratio < pair.minRatio) {
      throw new Error(
        `${pair.theme}.${pair.foreground} on ${pair.background} has contrast ${ratio.toFixed(2)}:1`,
      );
    }
  }
}

async function writeGeneratedOutputs(tokens) {
  const outputs = [
    {
      path: path.join(rootDir, "fe", "src", "styles", "generated-tokens.css"),
      content: renderCss(tokens),
    },
    {
      path: path.join(
        rootDir,
        "vnshop_mobile",
        "lib",
        "core",
        "design_system",
        "generated",
        "design_tokens.dart",
      ),
      content: renderDart(tokens),
    },
  ];

  for (const output of outputs) {
    await mkdir(path.dirname(output.path), { recursive: true });
    await writeFile(output.path, output.content, "utf8");
  }
}

async function main() {
  const tokens = await loadTokens(path.join(rootDir, "design-system", "tokens.json"));
  assertAccessiblePairs(tokens);
  await writeGeneratedOutputs(tokens);
}

if (process.argv[1] && pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url) {
  await main();
}
