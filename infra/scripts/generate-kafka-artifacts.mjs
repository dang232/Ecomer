#!/usr/bin/env node
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";

const root = process.cwd();
const canonicalPath = path.join(root, "infra", "kafka", "canonical-topics.json");
const topicsPath = path.join(root, "infra", "kafka", "kafka-topics.sh");
const aclsPath = path.join(root, "infra", "kafka", "kafka-acls.sh");

const fixtureFlag = process.argv.indexOf("--fixture");
const fixture = fixtureFlag >= 0 ? process.argv[fixtureFlag + 1] : undefined;
const canonical = JSON.parse(await readFile(canonicalPath, "utf8"));
if (fixture === "missing-topic") canonical.topics = [...canonical.topics, "fixture.topic.missing"];
if (fixture && fixture !== "missing-topic") throw new Error(`unknown fixture: ${fixture}`);

function fail(message) {
  throw new Error(`canonical Kafka inventory: ${message}`);
}

if (canonical.schemaVersion !== "kafka-canonical.v1") fail("unsupported schemaVersion");
const defaults = canonical.topicDefaults;
if (!defaults || defaults.partitions < 1 || defaults.replicationFactor < 1 || defaults.minInSyncReplicas < 1) {
  fail("topicDefaults must contain positive topic settings");
}

const topicNames = canonical.topics;
if (!Array.isArray(topicNames) || topicNames.length === 0 || new Set(topicNames).size !== topicNames.length) {
  fail("topics must be a non-empty list of unique names");
}
if (topicNames.some((name) => typeof name !== "string" || !/^[a-z0-9][a-zA-Z0-9.-]*$/.test(name))) {
  fail("topic names must use letters, digits, dots, and hyphens");
}

const topics = topicNames.map((name) => ({ name, ...defaults }));
const clients = canonical.clients ?? {};
const aclRows = canonical.acl ?? [];
const aclEntries = [];
const topicMatches = (pattern, topic) => pattern.endsWith(".*") ? topic.startsWith(pattern.slice(0, -1)) : pattern === topic;

for (const row of aclRows) {
  const principal = clients[row.service];
  if (!principal) fail(`ACL references unknown service ${row.service}`);
  for (const operation of ["read", "write"]) {
    for (const pattern of row[operation] ?? []) {
      const matchingTopics = topics.filter(({ name }) => {
        const baseName = name.replace(/\.(?:retry|DLT)$/, "");
        return topicMatches(pattern, name) || (baseName !== name && topicMatches(pattern, baseName));
      });
      if (matchingTopics.length === 0) fail(`ACL pattern ${pattern} for ${row.service} matches no canonical topic`);
      for (const topic of matchingTopics) {
        aclEntries.push({ principal, operation: operation === "read" ? "Read" : "Write", resourceType: "topic", resourceName: topic.name });
      }
    }
  }
  for (const group of canonical.groups?.[row.service] ?? []) {
    aclEntries.push({ principal, operation: "Read", resourceType: "group", resourceName: group });
  }
}

const aclKey = (entry) => `${entry.principal}|${entry.operation}|${entry.resourceType}|${entry.resourceName}`;
const uniqueAcls = [...new Map(aclEntries.map((entry) => [aclKey(entry), entry])).values()]
  .sort((left, right) => aclKey(left).localeCompare(aclKey(right)));

function header(title) {
  return `#!/usr/bin/env bash\n# Generated by infra/scripts/generate-kafka-artifacts.mjs. Do not edit.\n# ${title}\nset -euo pipefail\n\nBROKER="\${KAFKA_BOOTSTRAP_SERVERS:-kafka:9092}"\nADMIN_CONFIG="\${KAFKA_ADMIN_CONFIG:-/tmp/admin.properties}"\ntest -f "$ADMIN_CONFIG" || { echo "Kafka admin config is required: $ADMIN_CONFIG" >&2; exit 65; }\n\n`;
}

const topicScript = header("Canonical Kafka topic creation") + topics.map((topic) =>
  `kafka-topics --bootstrap-server "$BROKER" --command-config "$ADMIN_CONFIG" --create --if-not-exists --topic ${topic.name} --partitions ${topic.partitions} --replication-factor ${topic.replicationFactor} --config min.insync.replicas=${topic.minInSyncReplicas}`
).join("\n") + "\n";

const aclScript = header("Canonical Kafka ACL creation") + uniqueAcls.map((entry) => {
  const resourceFlag = entry.resourceType === "topic" ? "--topic" : "--group";
  return `kafka-acls --bootstrap-server "$BROKER" --command-config "$ADMIN_CONFIG" --add --allow-principal User:${entry.principal} --operation ${entry.operation} ${resourceFlag} ${entry.resourceName}`;
}).join("\n") + "\n";

async function expected(pathname, contents) {
  try {
    return (await readFile(pathname, "utf8")) === contents;
  } catch (error) {
    if (error.code === "ENOENT") return false;
    throw error;
  }
}

const check = process.argv.includes("--check");
const current = await Promise.all([expected(topicsPath, topicScript), expected(aclsPath, aclScript)]);
if (check) {
  if (!current.every(Boolean)) {
    console.error("Kafka generated artifacts are stale. Run node infra/scripts/generate-kafka-artifacts.mjs");
    process.exitCode = 1;
  } else {
    console.log(`Kafka generated artifacts are current (${topics.length} topics, ${uniqueAcls.length} ACLs).`);
  }
} else {
  await writeFile(topicsPath, topicScript, "utf8");
  await writeFile(aclsPath, aclScript, "utf8");
  console.log(`Generated ${topicsPath} and ${aclsPath} (${topics.length} topics, ${uniqueAcls.length} ACLs).`);
}
